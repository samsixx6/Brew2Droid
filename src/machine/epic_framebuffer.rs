//! Porta os getters privados de framebuffer de Epic, Dark Slayer e Rice Cake para o IDIB público.
//! O código substituto é Thumb/AAPCS e chama as tabelas reais de IDisplay/IBitmap/IDIB.
//! Não escolhe modelo nem endereço físico. Os stubs ARM/Thumb estão em
//! epic_framebuffer.S (três variantes) e rice_framebuffer.S.
use super::*;
use crate::save_state::{Erro, Leitor};

#[derive(Clone, Copy)]
pub(super) enum EpicFramebufferPort {
    One,
    Two,
    Dark,
    Rice,
}
impl EpicFramebufferPort {
    pub(super) fn select(module: &str, mif: &str) -> Option<Self> {
        PAIRS
            .iter()
            .find(|&&(m, f, _)| module.eq_ignore_ascii_case(m) && mif.eq_ignore_ascii_case(f))
            .map(|&(_, _, port)| port)
    }
    fn at(self) -> u32 {
        match self {
            Self::One => 0x10034310,
            Self::Two => 0x1000c34c,
            Self::Dark => 0x10002ee8,
            Self::Rice => 0x201d4,
        }
    }
    fn end(self) -> u32 {
        match self {
            Self::One => 0x100349ba,
            Self::Two => 0x1000c52c,
            Self::Dark => 0x100031b4,
            Self::Rice => 0x202a8,
        }
    }
    fn region(self) -> &'static str {
        if matches!(self, Self::Rice) {
            "module"
        } else {
            "heap"
        }
    }
    fn heap_image(self) -> Option<(u32, u32, [u8; 8])> {
        match self {
            Self::One => Some((0x100337f8, 0x24e8, [0, 0, 0, 0x31, 0xc8, 0x37, 3, 0x10])),
            Self::Two => Some((0x10000000, 0x23a48, [0, 0, 1, 0, 0, 0, 0, 0x31])),
            Self::Dark => Some((0x10000000, 0x24108, [0, 0, 1, 0, 0, 0, 0, 0x31])),
            Self::Rice => None,
        }
    }
    // No Epic I o primeiro word publica HELPERS após a descompactação; o segundo
    // continua eafffffe até depois do getter. Cobrá-lo atrasava a porta e conservava
    // o descritor NULL já produzido, embora o código acabasse corrigido mais tarde.
    fn published(self, header: &[u8], expected: &[u8; 8]) -> bool {
        if matches!(self, Self::One) {
            header.get(..4) == Some(&expected[..4])
        } else {
            header == expected
        }
    }
    fn old(self) -> &'static [u8] {
        match self {
            Self::One => &OLD_ONE,
            Self::Two => &OLD_TWO,
            Self::Dark => &OLD_DARK,
            Self::Rice => &OLD_RICE,
        }
    }
    fn fixed(self) -> &'static [u8] {
        match self {
            Self::One => &PUBLIC_ONE,
            Self::Two => &PUBLIC_TWO,
            Self::Dark => &PUBLIC_DARK,
            Self::Rice => &PUBLIC_RICE,
        }
    }
    // O corpo inteiro conta, inclusive LR em uma API chamada pelo getter antigo.
    fn inside(self, pc: u32) -> bool {
        (self.at()..self.end()).contains(&(pc & !1))
    }
}
