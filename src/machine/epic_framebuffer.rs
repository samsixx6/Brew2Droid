impl<C: CpuBackend> Machine<C> {
    pub(super) fn apply_epic_public_framebuffer(&mut self, pc: u32) -> Result<(), CpuError> {
        let Some(port) = self.epic_public_framebuffer else {
            return Ok(());
        };
        // O segundo módulo verifica sua integridade antes de CreateInstance. O primeiro
        // descompacta uma biblioteca depois disso e publica HELPERS só quando terminou.
        if self.applet_class == 0 {
            return Ok(());
        }
        if let Some((base, size, published)) = port.heap_image() {
            if self.heap.size_of(base) != Some(size) {
                return Ok(());
            }
            let mut header = [0; 8];
            if self.cpu.read_mem(base, &mut header).is_err() || !port.published(&header, &published)
            {
                return Ok(());
            }
        } else {
            // Rice é código do módulo, sem descompactação tardia. O helper original
            // GetAppInstance continua em uso; tanto template como cópia viva são guardados.
            if !self.rice_framebuffer_template_valid() {
                return Ok(());
            }
            let mut app_getter = [0; 24];
            if self.cpu.read_mem(0x1dd70, &mut app_getter).is_err() || app_getter != RICE_GET_APP {
                return Ok(());
            }
        }
        let mut live = vec![0; port.old().len()];
        if self.cpu.read_mem(port.at(), &mut live).is_err() || live != port.old() {
            return Ok(());
        }
        if port.inside(pc) || port.inside(self.cpu.read_reg(Reg::Lr)) {
            return Ok(());
        }
        // write_mem invalida também os blocos já traduzidos pelo JIT. O template
        // permanece original para a verificação de integridade na próxima inicialização;
        // Epic/Dark usam o heap descompactado, Rice usa a cópia viva do módulo.
        self.cpu.write_mem(port.at(), port.fixed())
    }

    fn rice_framebuffer_template_valid(&self) -> bool {
        self.module.mem.read(0x201d4, OLD_RICE.len() as u32).ok() == Some(OLD_RICE.as_slice())
            && self
                .module
                .mem
                .read(0x1dd70, RICE_GET_APP.len() as u32)
                .ok()
                == Some(RICE_GET_APP.as_slice())
    }

    pub(super) fn prepare_epic_public_framebuffer_restore(
        &self,
        name: &str,
        base: u32,
        bytes: &mut [u8],
        leitor: &Leitor<'_>,
        regs: &[u32],
    ) -> Result<(), Erro> {
        let Some(port) = self.epic_public_framebuffer else {
            return Ok(());
        };
        if name != port.region() {
            return Ok(());
        }
        let fail = || {
            Erro::Secao {
            nome: format!("mem.{}", port.region()),
            motivo:
                "o adaptador público de framebuffer não corresponde ao código e à fase do carregador verificados"
                    .into(),
        }
        };
        let scalars = leitor.u32s("esc.numeros")?;
        let class = scalars.get(7).copied().ok_or_else(fail)?;
        // Antes de CreateInstance o loader ainda pode conferir ou descompactar código.
        if class == 0 {
            return Ok(());
        }
        if let Some((image, size, published)) = port.heap_image() {
            let live = leitor.pares("heap.live")?;
            let block = live
                .iter()
                .find(|&&(at, _)| at == image)
                .map(|&(_, len)| len);
            let offset = image.checked_sub(base).ok_or_else(fail)? as usize;
            let header = bytes.get(offset..offset + 8);
            if block.is_none() && matches!(port, EpicFramebufferPort::One) {
                // Só a ausência da alocação e de seu cabeçalho prova a fase ainda não carregada.
                if live.iter().any(|&(at, len)| {
                    at <= image && u64::from(image) < u64::from(at) + u64::from(len)
                }) || header.is_some_and(|header| port.published(header, &published))
                {
                    return Err(fail());
                }
                return Ok(());
            }
            if block != Some(size)
                || !header.is_some_and(|header| port.published(header, &published))
            {
                return Err(fail());
            }
        } else {
            let offset = 0x1dd70u32.checked_sub(base).ok_or_else(fail)? as usize;
            if !self.rice_framebuffer_template_valid()
                || bytes.get(offset..offset + 24) != Some(RICE_GET_APP.as_slice())
            {
                return Err(fail());
            }
        }
        let offset = port.at().checked_sub(base).ok_or_else(fail)? as usize;
        let code = bytes
            .get_mut(offset..offset + port.old().len())
            .ok_or_else(fail)?;
        if code == port.fixed() {
            return Ok(());
        }
        if code != port.old() || port.inside(regs[15]) || port.inside(regs[14]) {
            return Err(fail());
        }
        code.copy_from_slice(port.fixed());
        Ok(())
    }
}

