fn exact_pairs_scan_the_known_allocation_instead_of_assuming_header_size() {
    for case in 0..3 {
        let mut m = machine(case);
        assert!(m.set_handset_runtime_identity(CASES[case].0, CASES[case].1));
        for (offset, reserved) in [(36, 40), (36, 48), (36, 64), (52, 64), (64, 80)] {
            assert_eq!(
                calibrate(&mut m, case, offset, reserved),
                offset,
                "case {case}, offset {offset}, reserved {reserved}"
            );
        }
    }
}
#[test]
fn calibration_patch_is_live_jit_safe_and_idempotent() {
    let mut m = machine(2);
    assert_eq!(calibrate(&mut m, 2, 36, 48), 48);
    assert!(m.set_handset_runtime_identity(CASES[2].0, CASES[2].1));
    assert_eq!(calibrate(&mut m, 2, 36, 48), 36);
    let before = m.dump(CASES[2].2, 460).unwrap();
    assert!(m.set_handset_runtime_identity(CASES[2].0, CASES[2].1));
    assert_eq!(m.dump(CASES[2].2, 460).unwrap(), before);
}

