fn unstarted(case: usize) -> Machine<BackendPadrao> {
    let (_, _, base, function) = CASES[case];
    let mut data = vec![0; 0x24000];
    data[0x2368..0x2368 + TILER.len()].copy_from_slice(TILER);
    data[..8].copy_from_slice(&[0, 0, 0xa0, 0xe3, 0x1e, 0xff, 0x2f, 0xe1]);
    data[(base - 0x10000) as usize..(base - 0x10000) as usize + function.len()]
        .copy_from_slice(function);
    // O ARM original continua fazendo a varredura. Só o provedor de sondas retorna
    // um buffer e o custo de alocação controlados para separar pedido e reserva.
    for offset in [24usize, 48, 112, 256, 364, 416] {
        let word = u32::from_le_bytes(function[offset..offset + 4].try_into().unwrap());
        assert_eq!(word >> 24, 0xeb);
        let delta = ((word << 8) as i32) >> 6;
        let target = (base + offset as u32 + 8).wrapping_add_signed(delta);
        let probe = offset == 24 || offset == 48 || offset == 364;
        let stub: Vec<u32> = if probe {
            vec![0xe5900084, 0xe12fff1e]
        } else {
            vec![0xe12fff1e]
        };
        for (i, word) in stub.iter().enumerate() {
            let at = (target - 0x10000) as usize + i * 4;
            data[at..at + 4].copy_from_slice(&word.to_le_bytes());
        }
    }
    let root = std::path::PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("local-tests/startup-repairs-wave20-20261031/graphics/calibration-fixture");
    let storage = StoragePaths::from_root(root.join("runtime"));
    let image = ModImage::parse(data).unwrap();
    Machine::new_with_storage_geometry(
        BackendPadrao::new().unwrap(),
        loader::load_with(&image, &[]).unwrap(),
        &root,
        &storage,
        None,
        DisplayGeometry {
            width: 240,
            height: 320,
            depth: 16,
        },
    )
    .unwrap()
}
fn machine(case: usize) -> Machine<BackendPadrao> {
    let mut m = unstarted(case);
    assert_eq!(m.run(1000).unwrap(), Outcome::Returned { code: 0 });
    m
}
fn calibrate(m: &mut Machine<BackendPadrao>, case: usize, offset: u32, reserved: u32) -> u32 {
    let ctx = loader::HEAP_BASE;
    let buffer = ctx + 0x200;
    let mut native = vec![0; reserved as usize];
    native[16..18].copy_from_slice(&[31, 248]);
    native[offset as usize..offset as usize + 2].copy_from_slice(&[31, 248]);
    native[(offset + 4) as usize..].fill(10);
    m.cpu_mut().write_mem(buffer, &native).unwrap();
    m.cpu_mut().write_mem(ctx, &vec![0; 0x100]).unwrap();
    for (at, v) in [(0x20, 16u32), (0x40, buffer), (0x84, reserved)] {
        m.cpu_mut().write_mem(ctx + at, &v.to_le_bytes()).unwrap();
    }
    let r = m.call_guest(CASES[case].2, [ctx, 0, 0, 0], 50000).unwrap();
    assert!(matches!(r, Outcome::Returned { .. }), "{r:?}");
    u32::from_le_bytes(m.dump(ctx + 0x50, 4).unwrap().try_into().unwrap())
}
